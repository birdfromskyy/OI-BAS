/**
 * Объекты, где пилот распоряжается только своим (сноска ²). Читать чужое ему
 * можно — в журнале полётов компании видны все записи, — а создавать,
 * менять и отмечать только собственное.
 */
const OWN_ONLY: Scope[] = ['документы', 'запись', 'фиксация'];

/** Принадлежность записи текущему пользователю; не задана — считаем своей */
export type Ownership = { own?: boolean };

function granted(role: Role, action: Action, scope: Scope, ctx: Ownership): boolean {
	const rights = MATRIX[scope][role] ?? '';

	// создающий видит созданное: «C» в матрице означает право провести проверку,
	// а не запрет открыть её протокол — иначе пилот не мог бы прочитать
	// собственное прохождение, на которое ссылается запись полёта (ФТ-10.7)
	if (action === 'R' && rights !== '') return true;
	if (!rights.includes(action)) return false;

	// чужой план пилот видит, но не трогает; создание чужого плана — тоже чужое
	if (role === 'пилот' && OWN_ONLY.includes(scope) && ctx.own === false) return false;

	return true;
}

/**
 * Может ли пользователь с этими ролями сделать это с этим объектом.
 * Роли складываются: администратор-пилот получает права обеих (2.1).
 */
export function can(
	roles: readonly string[],
	action: Action,
	scope: Scope,
	ctx: Ownership = {}
): boolean {
	return roles.some((r) => isRole(r) && granted(r, action, scope, ctx));
}

/** Строка из данных — известная роль? Роли приходят из карточки пользователя */
export function isRole(value: string): value is Role {
	return (ROLES as readonly string[]).includes(value);
}

/**
 * Кто какие роли раздаёт (ФТ-1.2). Право менять пользователей само по себе
 * не даёт права раздать любую роль: администратор не назначает администраторов —
 * это зона владельца (2.1), иначе повышение себя до владельца делается в два
 * шага и вся политика превращается в список подписей.
 *
 * Роли владельца нет ни у кого: владелец в компании один, и роль не выдаётся,
 * а передаётся — прежний владелец её при этом теряет.
 */
const ASSIGNABLE: Record<Role, Role[]> = {
	владелец: ['администратор', 'пилот', 'наблюдатель'],
	администратор: ['пилот', 'наблюдатель'],
	пилот: [],
	наблюдатель: []
};

/** Роли, которые этот пользователь может выдать и снять */
export function assignableBy(roles: readonly string[]): Role[] {
	const own = new Set<Role>();
	for (const r of roles) {
		if (isRole(r)) for (const a of ASSIGNABLE[r]) own.add(a);
	}
	return ROLES.filter((r) => own.has(r));
}

