/** Чеклист борта; если своего нет — шаблон его модели (ФТ-4.1, ФТ-4.2) */
export function checklistFor(aircraftId: string, model: string): Checklist | undefined {
	return (
		CHECKLISTS_MOCK.find((c) => c.aircraftId === aircraftId) ??
		CHECKLISTS_MOCK.find((c) => c.aircraftId === '' && c.model === model)
	);
}
