/**
 * Тип пункта (ФТ-4.6). Определяет, чем пилот отвечает:
 * кнопками да/нет, числом, выбором из списка, текстом, фотографией или подписью.
 */
/**
 * Тип ответа на пункт (ФТ-4.6).
 *
 * Подписи здесь нет: подписывают проведённую проверку целиком, а не строку
 * в списке, и подпись живёт в самом прохождении рядом с датой и координатами
 * (ФТ-6.8). Фотофиксации нет как типа: фотографию можно приложить к любому
 * пункту (ФТ-6.6), и отдельный пункт «сделать снимок» этому только мешал.
 */
export type ItemKind = 'да/нет' | 'число' | 'выбор' | 'текст';

/** Пункт чеклиста */
export type ChecklistItem = {
	id: string;
	title: string;
	/** Подсказка пилоту: что именно сделать (ФТ-4.9) */
	hint: string;
	kind: ItemKind;
	/** Для kind: 'число' — допустимый диапазон и единица измерения */
	min?: number;
	max?: number;
	unit?: string;
	/** Для kind: 'выбор' — варианты ответа */
	options?: string[];
	/** Заготовки примечаний: то, что пилот пишет чаще всего, чтобы не набирать руками */
	notes?: string[];
};

/**
 * Чеклист борта (ФТ-4.1–4.3, ФТ-4.10).
 *
 * У каждого борта свой чеклист. Пустой aircraftId означает шаблон модели:
 * его применяют ко всем бортам этой модели, а правка на уровне борта
 * создаёт собственную копию и шаблон не трогает.
 *
 * Версия неизменяема: план полёта ссылается на ту версию, по которой
 * выполнялась подготовка, поэтому правка чеклиста не переписывает историю.
 */
export type Checklist = {
	id: string;
	/** Ревизия строки на сервере; `version` ниже — версия самого чеклиста. */
	revision?: number;
	/** Борт из FLEET_MOCK. Пусто — шаблон уровня модели (ФТ-4.2) */
	aircraftId: string;
	/** Модель, для которой написан шаблон */
	model: string;
	title: string;
	version: number;
	/** Дата последнего изменения, ISO */
	updated: string;
	/** Кто изменил — пользователь из STAFF_MOCK */
	author: string;
	items: ChecklistItem[];
};

