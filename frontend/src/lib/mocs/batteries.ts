/** Состояние аккумулятора (ФТ-11.4) */
export type BatteryStatus = 'в строю' | 'на хранении' | 'на проверке' | 'выведен';

/**
 * Аккумулятор парка (ФТ-11).
 *
 * Принадлежит парку, а не борту: одна и та же батарея летает на разных
 * бортах, и привязка к борту потеряла бы её историю при первой же перестановке.
 *
 * Состояние батареи определяется не сроком и не числом циклов, а тем, что
 * она отдаёт под нагрузкой: ёмкость и токоотдача падают задолго до того,
 * как это станет заметно в полёте. Поэтому рядом с эталонными значениями
 * хранятся измеренные — по их отношению и считается износ.
 */
export type Battery = {
	id: string;
	revision?: number;
	/** Название батареи: им её и называют в парке, обычно серийный номер (ФТ-11.1) */
	serial: string;
	status: BatteryStatus;
	/** Дата ввода в эксплуатацию, ISO (ФТ-11.1) */
	started: string;
	/** Когда её последний раз проверяли: дата и время суток */
	checked: string;
	checkedAt: string;
	/** Ёмкость эталонная и измеренная, мА·ч */
	capacity: number;
	capacityNow: number;
	/** Токоотдача эталонная и измеренная, ампер */
	output: number;
	outputNow: number;
	note: string;
};

