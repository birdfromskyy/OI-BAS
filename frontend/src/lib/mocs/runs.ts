/** Ответ пилота по одному пункту чеклиста */
export type Answer = {
	itemId: string;
	/**
	 * Название пункта копией: чеклист потом правят и переименовывают,
	 * а протокол должен читаться и через год (ФТ-4.10).
	 */
	title: string;
	value: boolean | number | string | null;
	note: string;
};

/**
 * Прохождение чеклиста (ФТ-6).
 *
 * Отдельная запись, а не поля в полёте: подписанное прохождение неизменяемо,
 * а исправление вносится новым прохождением, прежнее сохраняется с причиной
 * аннулирования (ФТ-6.9). Поэтому у одного полёта их может быть несколько.
 */
export type Run = {
	id: string;
	revision?: number;
	/** Полёт, к которому относится проверка (ФТ-10.7) */
	flightId: string;
	pilotId?: string;
	checklistId: string;
	/** Название чеклиста на момент прохождения */
	checklist: string;
	/** Версия, по которой шли: правка чеклиста историю не трогает (ФТ-4.10) */
	version: number;

	/* Обязательные параметры прохождения */
	date: string;
	/** Начало и конец проверки, ЧЧ:ММ. Пустой конец — проверка не закончена */
	startedAt: string;
	finishedAt: string;
	site: string;
	/** Фактические координаты площадки, снятые устройством (ФТ-6.8) */
	lat: number;
	lon: number;
	weather: string;
	pilot: string;

	answers: Answer[];
	/** Описание всей проверки, а не отдельного пункта */
	description: string;
	/** Подпись: ФИО, дата и время (ФТ-6.8). Пустая — прохождение не подписано */
	signature: string;
	/** Причина аннулирования, если проверку переделали (ФТ-6.9) */
	voided: string;
};

