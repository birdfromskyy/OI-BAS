/** Жизненный цикл полёта (ФТ-5.7). «Завершён» и «отменён» — конечные состояния. */
export type FlightStatus =
	'черновик' | 'запланирован' | 'подготовка пройдена' | 'выполняется' | 'завершён' | 'отменён';

/**
 * Запись учёта полёта (ФТ-5.1, ФТ-10.1, ФТ-10.5–10.8).
 *
 * Одна запись описывает полёт на всём его пути: от плана до факта.
 * Отдельной сущности «план» нет — состояние различает поле status,
 * поэтому запланированный и выполненный полёт лежат в одной таблице
 * и не расходятся при переносе плана в журнал.
 */
export type FlightRecord = {
	id: string;
	/** Серверная ревизия записи; не показывается в интерфейсе. */
	revision?: number;
	no: number;
	date: string;
	status: FlightStatus;
	/** Ссылка на борт из FLEET_MOCK. Название подтягивается в mocs/rows.ts */
	aircraftId: string;
	/** Идентификатор выбранного чеклиста; название остаётся снимком для истории. */
	checklistId?: string;
	/** Ссылка на пользователя из STAFF_MOCK. ФИО подтягивается там же */
	pilotId: string;
	/**
	 * Название чеклиста, по которому шла подготовка (ФТ-5.2, ФТ-10.7).
	 * Хранится названием, а не ссылкой: чеклист правится и переименовывается,
	 * а в записи полёта должно остаться то, по чему проверяли.
	 */
	checklist: string;
	/** Прохождение чеклиста, по которому готовились (ФТ-10.7). Пусто — проверки не было */
	runId: string;
	/** Справочная площадка; её название и координаты остаются снимком полёта. */
	siteId?: string;
	site: string;
	lat: number;
	lon: number;
	task: string;
	takeoff: string;
	landing: string;
	duration: number;
	alt: number;
	/**
	 * Примечания пилота — свободный текст (ФТ-9.6).
	 * За полёт их может быть несколько, поэтому это массив, а пустой массив
	 * означает «примечаний нет». В отличие от машинных полей пишется человеком
	 * и кодом не разбирается: таблица показывает только их количество.
	 */
	notes: string[];
};

