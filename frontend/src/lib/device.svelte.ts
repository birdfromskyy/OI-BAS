import { MediaQuery } from 'svelte/reactivity';

/**
 * Телефон или планшет в руках пилота.
 *
 * Смотрим на ширину и на «грубый» указатель: узкое окно на ПК бывает у всех,
 * но вместе с пальцевым вводом это уже мобильное устройство. На сервере
 * ширина неизвестна, поэтому запасное значение — false: разметка приходит
 * настольной, а на телефоне переключается сразу после подключения скриптов.
 */
export const isPhone = new MediaQuery(
	'(max-width: 767px), (pointer: coarse) and (max-width: 1024px)',
	false
);

/**
 * Разделы, доступные с телефона: планируемые полёты, предполётная подготовка
 * выбранного из них полёта и приём приглашения — по ссылке приходят как раз
 * с телефона. Стартовый — список полётов.
 */
export const PHONE_ROUTES = ['/plan', '/list', '/join'];
export const PHONE_HOME = '/plan';
